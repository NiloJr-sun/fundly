"""Fundly local sync: reads `supabase status -o json` on stdin, writes the
git-ignored config.local.json and makes sure the two local test users in the
git-ignored .env.local exist. Passwords are random, local only, never printed."""

import json
import os
from pathlib import Path
import secrets
import sys
import urllib.error
import urllib.request

HERE = Path(__file__).resolve().parent
status = json.load(sys.stdin)
config = {
    'SUPABASE_URL': status['API_URL'],
    'SUPABASE_PUBLISHABLE_KEY': status['PUBLISHABLE_KEY'],
    'POWERSYNC_URL': 'http://127.0.0.1:55380',
}
assert config['SUPABASE_URL'].startswith('http://127.0.0.1:'), 'Not a local stack'
old_mask = os.umask(0o077)
(HERE / 'config.local.json').write_text(json.dumps(config, indent=2) + '\n')

env_file = HERE / '.env.local'
users = {}
if env_file.exists():
    for line in env_file.read_text().splitlines():
        if line.startswith('export ') and '=' in line:
            name, value = line[len('export '):].split('=', 1)
            users[name] = value
roles = {'A': 'first user', 'B': 'second user'}
for letter in roles:
    users.setdefault(f'FUNDLY_TEST_{letter}_EMAIL', f'fundly-local-{letter.lower()}@example.test')
    if not users.get(f'FUNDLY_TEST_{letter}_PASSWORD'):
        users[f'FUNDLY_TEST_{letter}_PASSWORD'] = secrets.token_urlsafe(24)
env_file.write_text(
    '# Fundly local sync test users (A and B).\n'
    '# Generated by up.sh for the local stack only. Git-ignored.\n'
    + ''.join(f'export {name}={value}\n' for name, value in sorted(users.items())))
os.umask(old_mask)


def call(path, body):
    request = urllib.request.Request(
        config['SUPABASE_URL'] + path, data=json.dumps(body).encode(), method='POST',
        headers={'apikey': config['SUPABASE_PUBLISHABLE_KEY'], 'Content-Type': 'application/json'})
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            return response.status
    except urllib.error.HTTPError as error:
        return error.code


for letter, role in roles.items():
    credentials = {'email': users[f'FUNDLY_TEST_{letter}_EMAIL'],
                   'password': users[f'FUNDLY_TEST_{letter}_PASSWORD']}
    if call('/auth/v1/token?grant_type=password', credentials) == 200:
        print(f'Test user {letter} ({role}) ready')
        continue
    status_code = call('/auth/v1/signup', credentials)
    assert status_code == 200, f'Creating test user {letter} failed with HTTP {status_code}'
    print(f'Test user {letter} ({role}) created')
print('Fundly local sync ready: Supabase', config['SUPABASE_URL'],
      '· PowerSync', config['POWERSYNC_URL'])
